"""Build the self-contained combo specialist shelf from pinned local checkouts.

Only explicitly selected support files are copied. Curated specialist notes are
reviewed source files in ``skills/combo/specialists``; this script never copies
upstream SKILL.md files, runs upstream scripts, installs packages, or fetches a
remote repository.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parents[1]
CURATION = ROOT / "curation" / "specialists.json"
LOCK = ROOT / "sources.lock.json"
SHELF = ROOT / "skills" / "combo"
REFERENCES = SHELF / "references"
KARPATHY_LICENSE_NOTICE = """Karpathy source-pack license notice

At the pinned commit, the source checkout's README identifies the project
license as MIT. The checkout has no standalone LICENSE file and supplies no
copyright-holder text. Preserve this notice with the provenance map and verify
the terms before redistributing adapted material.

Source: https://github.com/multica-ai/andrej-karpathy-skills/blob/2c606141936f1eeef17fa3043a72095b4765b9c2/README.md
"""


def read_json(path: Path) -> object:
    return json.loads(path.read_text(encoding="utf-8"))


def source_root(source: str) -> Path:
    """Resolve a repository-relative source path without allowing escape."""

    source_path = Path(source)
    if source_path.is_absolute() or ".." in source_path.parts:
        raise ValueError(f"source path must be repository-relative: {source}")
    resolved = (ROOT / source_path).resolve()
    if not resolved.is_relative_to(ROOT.resolve()):
        raise ValueError(f"source path escapes checkout: {source}")
    return resolved


def verify_pins(curation: dict, lock: list[dict]) -> None:
    locked = {row["pack"]: row["commit"] for row in lock}
    for row in curation["source_packs"]:
        if locked.get(row["name"]) != row["immutable_commit"]:
            raise ValueError(
                f"pin mismatch for {row['name']}: curation={row['immutable_commit']} "
                f"lock={locked.get(row['name'])}"
            )
        source = source_root(f"sources/{row['name']}/{row['primary_source']}")
        if not source.is_file():
            raise FileNotFoundError(source)
        for related in row.get("related_sources", []):
            source = source_root(f"sources/{row['name']}/{related['primary_source']}")
            if not source.is_file():
                raise FileNotFoundError(source)
    for row in curation["specialists"]:
        if row["immutable_commit"] != locked.get("ecc"):
            raise ValueError(
                f"specialist {row['id']} is not pinned to the ECC checkout"
            )
        source = source_root(row["primary_source"])
        if not source.is_file():
            raise FileNotFoundError(source)


def copy_bytes(src: Path, dst: Path, check: bool, changed: list[str]) -> None:
    if not src.is_file():
        raise FileNotFoundError(src)
    data = src.read_bytes()
    if dst.exists() and dst.read_bytes() == data:
        return
    changed.append(dst.relative_to(ROOT).as_posix())
    if not check:
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_bytes(data)


def render_source_map(curation: dict) -> str:
    lines = [
        "# Specialist source map",
        "",
        "This file is generated by `scripts/build-specialists.py` from",
        "`curation/specialists.json`. Every entry points to a pinned GitHub commit",
        "and a package-relative destination. The shelf contains adapted notes,",
        "not executable upstream skill entrypoints.",
        "",
        "## Source-pack decisions",
        "",
        "| Pack | Commit | Decision | Destination | License | Reason |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for row in curation["source_packs"]:
        lines.append(
            f"| {row['name']} | `{row['immutable_commit'][:12]}` | {row['decision']} | "
            f"`{row['destination']}` | [{row['license'].split('/')[-1]}](licenses/{row['license'].split('/')[-1]}) | {row['reason']} |"
        )
    matt = next(
        (row for row in curation["source_packs"] if row["name"] == "matt"), None
    )
    if matt and matt.get("related_sources"):
        lines += [
            "",
            "### Matt references adapted by the workflow owners",
            "",
            "| ID | Primary source | Commit | Decision | Destination | Reason |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
        for row in matt["related_sources"]:
            lines.append(
                f"| `{row['id']}` | [{row['id']}]({row['source_url']}) | "
                f"`{row['immutable_commit'][:12]}` | {row['decision']} | "
                f"`{row['destination']}` | {row['reason']} |"
            )
    lines += [
        "",
        "## Selected specialists",
        "",
        "| ID | Primary source | Commit | Decision | Destination | License | Reason |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in curation["specialists"]:
        source = row["source_url"]
        lines.append(
            f"| `{row['id']}` | [{row['title']}]({source}) | "
            f"`{row['immutable_commit'][:12]}` | {row['decision']} | "
            f"`{row['destination']}` | [ecc.txt](licenses/ecc.txt) | {row['reason']} |"
        )
    lines += [
        "",
        "## Archived sources",
        "",
        "These sources remain in the pinned checkout for audit and provenance, but",
        "are excluded from the active shelf because they would create competing",
        "workflow, memory, or orchestration owners.",
        "",
        "| Primary source | Commit | Decision | Reason |",
        "| --- | --- | --- | --- |",
    ]
    for row in curation["excluded_sources"]:
        lines.append(
            f"| `{row['primary_source']}` | `{row['immutable_commit'][:12]}` | "
            f"{row['decision']} | {row['reason']} |"
        )
    lines.append("")
    return "\n".join(lines)


def verify_relative_links() -> None:
    """Reject broken package-relative Markdown links in the built shelf."""

    broken: list[str] = []
    pattern = re.compile(r"\[[^\]]+\]\(([^)]+)\)")
    for document in sorted(SHELF.rglob("*.md")):
        text = document.read_text(encoding="utf-8")
        text = re.sub(
            r"(?m)^ {0,3}(`{3,}|~{3,})[^\n]*\n[\s\S]*?^ {0,3}\1\s*$", "", text
        )
        text = re.sub(r"(`+)[^\n]*?\1", "", text)
        for match in pattern.finditer(text):
            target = match.group(1).strip().split("#", 1)[0].split("?", 1)[0]
            if not target or target.startswith(("http://", "https://", "mailto:")):
                continue
            candidate = (document.parent / unquote(target)).resolve()
            if not candidate.exists():
                broken.append(f"{document.relative_to(ROOT).as_posix()}: {target}")
    if broken:
        raise ValueError(f"broken package-relative links: {broken}")


def build(check: bool = False) -> list[str]:
    curation = read_json(CURATION)
    lock = read_json(LOCK)
    if not isinstance(curation, dict) or not isinstance(lock, list):
        raise TypeError("Expected a curation object and a source lock list")
    verify_pins(curation, lock)
    changed: list[str] = []

    # Preserve the license for every source pack represented in build metadata.
    for pack in ("ecc", "karpathy", "ponytail", "matt"):
        destination = REFERENCES / "licenses" / f"{pack}.txt"
        source = ROOT / "sources" / pack / "LICENSE"
        if source.is_file():
            copy_bytes(source, destination, check, changed)
        elif pack == "karpathy":
            data = KARPATHY_LICENSE_NOTICE.encode("utf-8")
            if not destination.exists() or destination.read_bytes() != data:
                changed.append(destination.relative_to(ROOT).as_posix())
                if not check:
                    destination.parent.mkdir(parents=True, exist_ok=True)
                    destination.write_bytes(data)
        else:
            raise FileNotFoundError(source)

    # Copy only explicitly declared support globs. Preserve each sidecar's
    # relative path so links from the adapted note remain meaningful.
    for row in curation["specialists"]:
        support_destination = row.get("support_destination")
        if row.get("support_files") and not support_destination:
            raise ValueError(f"support destination missing for {row['id']}")
        for pattern in row.get("support_files", []):
            pattern_path = Path(pattern)
            base = source_root(pattern_path.parent.as_posix())
            if ".." in pattern_path.parts or not base.is_dir():
                raise ValueError(f"invalid support path: {pattern}")
            for source in sorted(base.glob(pattern_path.name)):
                if source.is_file():
                    relative = source.relative_to(base)
                    destination = ROOT / support_destination / relative
                    copy_bytes(source, destination, check, changed)

    map_destination = REFERENCES / "source-map.md"
    rendered = render_source_map(curation).encode("utf-8")
    if map_destination.exists() and map_destination.read_bytes() == rendered:
        pass
    else:
        changed.append(map_destination.relative_to(ROOT).as_posix())
        if not check:
            map_destination.parent.mkdir(parents=True, exist_ok=True)
            map_destination.write_bytes(rendered)

    expected = {Path(row["destination"]).as_posix() for row in curation["specialists"]}
    actual = {
        path.relative_to(ROOT).as_posix()
        for path in (SHELF / "specialists").glob("*.md")
        if path.name != "INDEX.md"
    }
    missing = sorted(expected - actual)
    extra = sorted(actual - expected)
    if missing or extra:
        raise ValueError(
            f"specialist note set mismatch: missing={missing}, extra={extra}"
        )

    # A nested SKILL.md would advertise a competing entrypoint after install.
    nested = sorted(
        path.relative_to(ROOT).as_posix()
        for path in SHELF.rglob("SKILL.md")
        if path.resolve() != (SHELF / "SKILL.md").resolve()
    )
    if nested:
        raise ValueError(f"nested SKILL.md entrypoints are forbidden: {nested}")
    verify_relative_links()
    return changed


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="validate pins, links, and generated bytes without writing files",
    )
    args = parser.parse_args()
    changed = build(check=args.check)
    mode = "would change" if args.check else "changed"
    print(json.dumps({"mode": mode, "files": changed, "count": len(changed)}))


if __name__ == "__main__":
    main()
